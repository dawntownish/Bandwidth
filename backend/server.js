const PORT = process.env.PORT || 3000;

// Two providers. Fill in whichever you have; if only one is set, it handles everything.
const PROVIDERS = {
  // Muse Spark through the Meta Model API
  spark: {
    label: "Muse Spark",
    url: process.env.META_API_URL || "",
    key: process.env.META_API_KEY || "", // <-- stays in .env, never in code
    model: process.env.META_MODEL || "",
  },
  // The open-weight model (Meta Llama on Groq by default). Any host that speaks the "chat completions"
  // format works: Groq, OpenRouter, Baseten, Together, a local server... Just change the three OPEN_ lines in .env.
  open: {
    label: process.env.OPEN_LABEL || "an open-weight Meta model", // shown in the app as "AI-generated by ..."
    url: process.env.OPEN_API_URL || "https://api.groq.com/openai/v1/chat/completions",
    key: process.env.OPEN_API_KEY || "",
    model: process.env.OPEN_MODEL || "llama-3.3-70b-versatile",
  },
};

// Which model does which job. Change these to re-route a feature.
const TASK_PROVIDER = { summary: "open", complexity: "spark", chemistry: "spark" };

function configured(p) { return !!(p.key && p.url && p.model); }

// ---------- the ONE place that talks to a model ----------
async function callModel(prompt, task) {
  const first = TASK_PROVIDER[task] || "spark";
  const second = first === "spark" ? "open" : "spark";
  const name = configured(PROVIDERS[first]) ? first : configured(PROVIDERS[second]) ? second : null;
  if (!name) return { ok: false, error: "not_configured" };
  const p = PROVIDERS[name];
  console.log(`[${task}] using ${p.label}`);

  try {
    // Chat Completions format (both Meta Model API and Baseten document this endpoint).
    const body = {
      model: p.model,
      temperature: 0, // pick the same sentences every time
      messages: [{ role: "user", content: prompt }],
    };
    // Glimmer can "think" before answering. A low setting keeps it fast. Set OPEN_REASONING_EFFORT in .env (low / medium / high).
    if (p === PROVIDERS.open && process.env.OPEN_REASONING_EFFORT) body.reasoning_effort = process.env.OPEN_REASONING_EFFORT;
    const send = () => fetch(p.url, {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: `Bearer ${p.key}` },
      body: JSON.stringify(body),
    });
    let res = await send();
    if (res.status === 429) { // free tiers have per-minute limits: wait a moment and try once more
      await new Promise((r) => setTimeout(r, 2500));
      res = await send();
    }
    if (res.status === 429) return { ok: false, error: "rate_limited" };
    if (!res.ok) {
      // Shows WHY it failed in this terminal (never prints your key).
      const detail = (await res.text()).slice(0, 400);
      console.error(`${p.label} error ${res.status}: ${detail}`);
      return { ok: false, error: "model_error" };
    }
    const json = await res.json();
    const text = json && json.choices && json.choices[0] && json.choices[0].message
      ? json.choices[0].message.content
      : null;
    if (typeof text !== "string") return { ok: false, error: "model_error" };
    // Some models print their thinking inside <think> tags. Drop it, keep only the answer.
    return { ok: true, text: text.replace(/<think>[\s\S]*?<\/think>/gi, "").trim(), via: p.label };
  } catch (err) {
    console.error(`Could not reach ${p.label}:`, err.message);
    return { ok: false, error: "model_error" };
  }
}

function parseJson(text) {
  const clean = text.replace(/```json|```/g, "").trim();
  try {
    return JSON.parse(clean);
  } catch (err) {
    // The model added words around the JSON: take the part between the first { and the last }.
    const a = clean.indexOf("{"), b = clean.lastIndexOf("}");
    if (a !== -1 && b > a) { try { return JSON.parse(clean.slice(a, b + 1)); } catch (e) { /* fall through */ } }
    return null;
  }
}

// ---------- features ----------
const TIER_FRACTION = { light: 0.25, medium: 0.5, full: 0.75 };

async function summary({ text, tier }) {
  if (typeof text !== "string" || !text.trim()) return { ok: false, error: "bad_request" };
  const sentences = splitSentences(text).map((s) => s.trim()).filter(Boolean);
  if (sentences.length < 3) return { ok: false, error: "too_short" };

  const fraction = TIER_FRACTION[tier] || TIER_FRACTION.medium;
  const n = Math.max(1, Math.round(sentences.length * fraction));

  const prompt =
    `You are selecting sentences, not writing. From the TEXT below, choose the ${n} most ` +
    `important sentences and copy each one EXACTLY, character for character. Do not ` +
    `paraphrase, merge, shorten or add anything. Return only JSON like ` +
    `{"sentences": ["...", "..."]}. If you cannot choose reliably, return {"sentences": []}.\n\nTEXT:\n${text}`;

  const out = await callModel(prompt, "summary");
  if (!out.ok) return out;

  const parsed = parseJson(out.text);
  const picked = parsed && Array.isArray(parsed.sentences) ? parsed.sentences : [];

  // Keep only sentences that really exist in the original, in original order.
  const verified = sentences.filter((orig) =>
    picked.some((p) => typeof p === "string" && appearsInSource(p, orig) && appearsInSource(orig, p))
  );

  if (!verified.length) return { ok: false, error: "unverified" };
  return { ok: true, data: { lines: verified }, via: out.via };
}

